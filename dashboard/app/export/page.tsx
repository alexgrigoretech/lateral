import type { Metadata } from "next";
import { Fragment } from "react";
import { CopyButton } from "@/components/copy-button";
import { DATASETS } from "@/lib/datasets";
import { exportFilename, exportHref, FORMATS, readManifest } from "@/lib/export";
import { utc } from "@/lib/format";
import { getMeta } from "@/lib/queries";

export const dynamic = "force-dynamic";
export const metadata: Metadata = { title: "Export the data" };

function datasetName(name: string) {
  const parts = name.split("_");
  return parts.map((part, index) => <Fragment key={index}>{part}{index < parts.length - 1 && <>_<wbr /></>}</Fragment>);
}

export default async function ExportPage() {
  const [meta, manifest] = await Promise.all([getMeta(), readManifest()]);
  return <div className="page">
    <header><h1 className="page__title">Export the data</h1><p className="page__lede">Download every dataset behind this site as CSV or Parquet. Parquet downloads are the committed files, byte for byte. CSV is converted from the same Parquet when you download it, and an unfiltered CSV of a report dataset matches its file in outputs/.</p></header>
    <section className="section" aria-labelledby="datasets-title"><h2 className="section__title" id="datasets-title">Datasets</h2>
      <div className="table-scroll" role="region" aria-label="Datasets and downloads" tabIndex={0}><table className="data-table data-table--static-head export-datasets">
        <caption>Datasets with row counts from the manifest</caption>
        <thead><tr><th scope="col">Dataset</th><th scope="col" className="num">Rows</th><th scope="col">Filters</th><th scope="col">Download</th><th scope="col">One row per</th><th scope="col">Business key</th></tr></thead>
        <tbody>{DATASETS.map(({ name, grain, key, filters }) => {
          const rows = manifest.files.find((file) => file.path.endsWith(`/${name}.parquet`))?.rows;
          const filterText = filters.join(", ") || "none";
          return <tr key={name}><th scope="row"><code>{datasetName(name)}</code></th><td className="num cell-num">{rows === 0 ? "0 (header only)" : rows ?? <span className="na">n/a</span>}</td><td>{filterText === "indicator, country" ? <span className="status-word status-word--muted">{filterText}</span> : filterText}</td><td>{FORMATS.map((format) => <a className="download-link" href={exportHref(name, format.value)} download={exportFilename(name, format.value)} key={format.value}>{format.label}<span className="visually-hidden">, {name}</span></a>)}</td><td>{grain}</td><td><code>{key}</code></td></tr>;
        })}</tbody>
      </table></div>
    </section>
    <section className="section" aria-labelledby="filter-title"><h2 className="section__title" id="filter-title">Filter a download</h2>
      <p>Use <code>/api/export/&lt;dataset&gt;?format=csv&amp;indicator=SP.POP.TOTL</code> and append <code>&amp;country=USA</code> to combine filters. Choose from {meta.indicators.length} indicator codes and {meta.countries.length} country codes. An unknown code or an unsupported filter returns HTTP 400 with a JSON error.</p>
      <p>Indicator codes: {meta.indicators.map((item, index) => <Fragment key={item.indicator_code}>{index > 0 && ", "}<code>{item.indicator_code}</code></Fragment>)}.</p>
      <p>Country codes: {meta.countries.map((item, index) => <Fragment key={item.country_iso3}>{index > 0 && ", "}<code>{item.country_iso3}</code></Fragment>)}.</p>
    </section>
    <section className="section" aria-labelledby="provenance-title"><h2 className="section__title" id="provenance-title">Provenance</h2>
      <p>Pipeline run {manifest.run_id}, exported at {utc(manifest.exported_at)}, generated by {manifest.generator}.</p>
      <p>Check the committed exports with <code>python -m wb_pipeline manifest --check</code>.</p>
      <p><a className="download-link manifest-link" href="/api/export/manifest" download="manifest.json">manifest.json</a></p>
      <div className="table-scroll" role="region" aria-label="Manifest files and SHA-256 digests" tabIndex={0}><table className="manifest-table data-table data-table--static-head">
        <caption>Exported files with row counts, sizes and SHA-256 digests</caption>
        <thead><tr><th scope="col">File</th><th scope="col" className="num">Rows</th><th scope="col" className="num">Bytes</th><th scope="col">SHA-256</th></tr></thead>
        <tbody>{manifest.files.map((file) => {
          const slash = file.path.lastIndexOf("/");
          const directory = file.path.slice(0, slash);
          const basename = file.path.slice(slash + 1);
          return <tr key={file.path}><th scope="row"><code>{directory}/<wbr />{basename}</code></th><td className="num cell-num">{file.rows === null ? <span className="na">n/a</span> : file.rows}</td><td className="num cell-num">{file.bytes.toLocaleString("en-US")}</td><td className="cell-id"><code className="hash">{file.sha256}</code> <CopyButton value={file.sha256} label="digest" /></td></tr>;
        })}</tbody>
      </table></div>
    </section>
  </div>;
}
